from dataclasses import dataclass

from app.orchestrator import WorkflowTask


@dataclass
class ScenarioDefinition:
    name: str
    requirement: str
    assumptions: list[str]
    risks: list[str]
    validation_steps: list[str]
    tasks: dict[str, WorkflowTask]


def build_greenfield_scenario() -> ScenarioDefinition:
    tasks = {
        "requirement_analysis": WorkflowTask(
            name="requirement_analysis",
        ),
        "architecture_design": WorkflowTask(
            name="architecture_design",
            dependencies=["requirement_analysis"],
        ),
        "security_review": WorkflowTask(
            name="security_review",
            dependencies=["requirement_analysis"],
        ),
        "implementation": WorkflowTask(
            name="implementation",
            dependencies=[
                "architecture_design",
                "security_review",
            ],
            requires_approval=True,
        ),
        "testing": WorkflowTask(
            name="testing",
            dependencies=["implementation"],
        ),
        "documentation": WorkflowTask(
            name="documentation",
            dependencies=["implementation"],
        ),
        "release_review": WorkflowTask(
            name="release_review",
            dependencies=[
                "testing",
                "documentation",
            ],
            requires_approval=True,
        ),
    }

    return ScenarioDefinition(
        name="greenfield",
        requirement=(
            "Build a new production-style URL shortener "
            "with redirect and click analytics."
        ),
        assumptions=[
            "Python and FastAPI are acceptable technologies.",
            "SQLite is acceptable for the prototype.",
            "Short codes are generated by the service.",
        ],
        risks=[
            "Short-code collisions.",
            "Invalid URLs.",
            "Database persistence failures.",
            "Unsafe autonomous release decisions.",
        ],
        validation_steps=[
            "Validate incoming URLs.",
            "Test unique short-code creation.",
            "Test redirect behavior.",
            "Verify analytics increments.",
            "Require approval before implementation and release.",
        ],
        tasks=tasks,
    )


