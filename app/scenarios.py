def build_ambiguous_scenario() -> ScenarioDefinition:
    tasks = {
        "requirement_interpretation": WorkflowTask(
            name="requirement_interpretation",
        ),
        "ambiguity_detection": WorkflowTask(
            name="ambiguity_detection",
            dependencies=["requirement_interpretation"],
        ),
        "human_clarification": WorkflowTask(
            name="human_clarification",
            dependencies=["ambiguity_detection"],
            requires_approval=True,
        ),
        "solution_design": WorkflowTask(
            name="solution_design",
            dependencies=["human_clarification"],
        ),
        "implementation": WorkflowTask(
            name="implementation",
            dependencies=["solution_design"],
            requires_approval=True,
        ),
        "security_validation": WorkflowTask(
            name="security_validation",
            dependencies=["implementation"],
        ),
        "release_review": WorkflowTask(
            name="release_review",
            dependencies=["security_validation"],
            requires_approval=True,
        ),
    }

    return ScenarioDefinition(
        name="ambiguous",
        requirement=(
            "Make shortened links more secure."
        ),
        assumptions=[
            "The phrase 'more secure' is not sufficiently specific.",
            "The system should not autonomously choose a "
            "high-impact interpretation.",
        ],
        risks=[
            "Implementing the wrong security control.",
            "Changing expected link behavior.",
            "Over-restricting legitimate redirects.",
            "Proceeding without stakeholder clarification.",
        ],
        validation_steps=[
            "Detect ambiguity before implementation.",
            "Pause for human clarification.",
            "Record the approved interpretation.",
            "Run security-focused validation.",
            "Require release approval.",
        ],
        tasks=tasks,
    )